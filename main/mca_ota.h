#pragma once
#include "esp_http_server.h"

/* Обновление прошивки по сети: POST /ota с файлом build/esp32_mca.bin,
 * GET /ota - версия и состояние слота. Разметка - partitions.csv. */

/* Печатает в консоль, из какого слота запущена прошивка и не было ли
 * отката. Вызывать при старте. */
void mca_ota_init(void);

/* Регистрирует /ota на веб-сервере (нужно 2 свободных обработчика). */
void mca_ota_register(httpd_handle_t srv);

/* Новая прошивка подтверждает себя на первом запросе страницы: до
 * этого загрузчик при перезагрузке вернёт прежнюю. Повторные вызовы
 * ничего не стоят. */
void mca_ota_confirm(void);
