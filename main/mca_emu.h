#pragma once
#include <stdbool.h>
#include <stdint.h>
#include "esp_err.h"

/* Эмуляция MCA по бинарному протоколу shproto на TCP-порту (8234 или свой,
 * см. mca_emu_set_port): программы
 * на ПК, умеющие работать с анализаторами AtomSpectra по сети (например,
 * BecqMoni, «AtomSpectra TCP»), видят прибор как такой анализатор. Прибор
 * объявляет себя в сети (mDNS _atomspectra._tcp). Подробности - в
 * mca_emu.c и README. */

/* Загрузить настройку и, если эмуляция включена (по умолчанию - да),
 * запустить её. Вызывать после старта сети и mca_settings_load(). */
void      mca_emu_init(void);

/* 0 - выключить, иначе включить. Сохраняется в памяти прибора и действует
 * сразу. */
esp_err_t mca_emu_set(uint32_t on);

/* Включена ли эмуляция. */
bool      mca_emu_on(void);

/* Адрес подключённого клиента, "" - никого. */
const char *mca_emu_client(void);

/* TCP-порт эмуляции (по умолчанию 8234). Новый порт - от 1024 до 65535
 * (ниже - служебные, 80 занят страницей прибора), иначе
 * ESP_ERR_INVALID_ARG. Сохраняется в памяти прибора; если эмуляция
 * включена, сервер сразу перезапускается на новом порту. */
esp_err_t mca_emu_set_port(uint32_t port);
uint16_t  mca_emu_port(void);

/* Порт открыт и ждёт подключений (false - выключено или порт не открылся,
 * сервер повторяет попытку раз в 2 с). */
bool      mca_emu_listening(void);
