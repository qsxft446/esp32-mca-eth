#pragma once
#include <stdint.h>

/* ОКНО БЫСТРОГО CPS И МОЩНОСТИ ДОЗЫ: накопление + детектор изменений CUSUM.
 *
 * Каждые ~100 мс приходит интервал: события, длительность, суммы весов дозы.
 * Пока счёт ровный, окно растёт до CPSW_K интервалов (30 с) - цифра точнее.
 * Две накопленные суммы логарифма отношения правдоподобия (Пуассон):
 * «скорость выросла в CPSW_R раза» и «упала в CPSW_R раза» против средней
 * по окну. Сумма выше CPSW_H - изменение: окно сокращается до интервалов с
 * того места, где сумма начала расти, и цифра сразу считается по новым
 * данным. Окно пустое (скорость 0), а события пошли - окно начинается
 * заново.
 *
 * Модель (tools/cpswin.py, фон 30 имп/с): в покое ±3.3 % (окно 10 с -
 * ±5.5 %), ложный сброс раз в ~20 мин; источник x2 - половина скачка за
 * 0.9 с, x10 - 0.1 с, убрали (/2) - 1.9 с, x1.5 - 2.4 с.
 * tools/cpswin.py - построчный порт: меняется одно - меняется второе. */

#define CPSW_K 300          /* интервалов в окне не больше: 30 с по 0.1 с */
#define CPSW_R 1.5          /* какое изменение скорости ищем              */
#define CPSW_H 8.0          /* порог суммы: ложный сброс раз в ~20 мин    */

typedef struct {
    uint32_t c[CPSW_K];     /* событий за интервал                        */
    uint32_t d[CPSW_K];     /* длительность интервала, мкс                */
    float    h[CPSW_K];     /* сумма весов H*(10), пЗв                    */
    float    k[CPSW_K];     /* сумма весов кермы, пГр                     */
    int      head, n;       /* куда писать следующий; интервалов в окне  */
    double   su, sd;        /* суммы CUSUM вверх и вниз                   */
    int      zu, zd;        /* сколько интервалов подряд сумма > 0        */
    uint32_t steps;         /* шагов с последнего сброса (для сверки)     */
} cpsw_t;

void cpsw_reset(cpsw_t *w);
void cpsw_step(cpsw_t *w, uint32_t dc, uint32_t dd_us, float dh, float dk);
/* Итог окна: событий, длительность (мкс), суммы весов дозы, интервалов. */
void cpsw_sum(const cpsw_t *w, uint64_t *cnt, uint64_t *dur_us,
              double *h, double *k, int *n);
